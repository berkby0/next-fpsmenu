function _U(str, ...)
    local lang = (Config and Config.Locale) or 'en'
    if Locales[lang] and Locales[lang][str] then
        return string.format(Locales[lang][str], ...)
    elseif Locales['en'] and Locales['en'][str] then
        return string.format(Locales['en'][str], ...)
    elseif Locales['tr'] and Locales['tr'][str] then
        return string.format(Locales['tr'][str], ...)
    else
        return str
    end
end
